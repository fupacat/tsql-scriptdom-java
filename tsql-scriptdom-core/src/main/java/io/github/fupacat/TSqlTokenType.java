package io.github.fupacat;

public enum TSqlTokenType {
    None,
    EndOfFile,
    WhiteSpace,
    SingleLineComment,
    MultilineComment,
    Identifier,
    QuotedIdentifier,
    AsciiStringOrQuotedIdentifier,
    AsciiStringLiteral,
    UnicodeStringLiteral,
    IntegerLiteral,
    NumericLiteral,
    RealLiteral,
    MoneyLiteral,
    BinaryLiteral,
    Variable,

    // Keywords
    Select,
    From,
    Where,
    Insert,
    Update,
    Delete,
    Create,
    Alter,
    Drop,
    Table,
    View,
    Index,
    Procedure,
    Function,
    Trigger,
    Database,
    Schema,
    As,
    On,
    In,
    Into,
    Values,
    Set,
    By,
    Group,
    Order,
    Having,
    Join,
    Inner,
    Left,
    Right,
    Full,
    Outer,
    Cross,
    Union,
    All,
    Distinct,
    Top,
    With,
    Exec,
    Execute,
    Begin,
    End,
    If,
    Else,
    While,
    Return,
    Declare,
    Case,
    When,
    Then,
    And,
    Or,
    Not,
    Is,
    Null,
    Like,
    Between,
    Exists,

    // Symbols
    LeftParenthesis,
    RightParenthesis,
    LeftCurly,
    RightCurly,
    Comma,
    Semicolon,
    Dot,
    EqualsSign,
    Plus,
    Minus,
    Multiply,
    Divide,
    Modulo,
    LessThan,
    GreaterThan,
    Bang,
    BitwiseAnd,
    BitwiseOr,
    BitwiseXor,

    // Fallback
    CustomToken;

    // TRACEABILITY_MAPPING: REQ-006
    public boolean _isComment() {
        return this == SingleLineComment || this == MultilineComment;
    }

    // TRACEABILITY_MAPPING: REQ-006
    public boolean _isWhitespaceOrComment() {
        return this == WhiteSpace || this == SingleLineComment || this == MultilineComment;
    }
}
